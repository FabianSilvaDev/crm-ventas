/**
 * Sprites de la oficina: personajes, muebles y globos de estado.
 *
 * Los personajes pasan de 16x16 a **24x32**, con la proporcion de los simuladores de
 * personajes de consola (cabeza en torno a un tercio de la altura) y tres tonos de piel
 * y dos de pelo, que es lo que da volumen sin salirse del pixel art.
 *
 * La referencia de estilo es la de los RPG de personajes de los anos 2010 (personajes
 * altos, contorno marcado, sombra lateral): la ESTRUCTURA, no los personajes. Todo lo que
 * hay aqui esta dibujado para este proyecto.
 *
 * Cada matriz tiene filas de la MISMA longitud; `assertMatrix` lo comprueba al cargar el
 * modulo, y `tools/check-sprites.mjs` lo imprime en ASCII para revisarlo a ojo.
 *
 * Los personajes se componen en tres capas:
 *   cuerpo (silueta) + peinado + accesorio
 * de modo que 2 cuerpos x 4 peinados x 4 accesorios x 8 acentos x 4 pieles dan variedad
 * suficiente para toda la plantilla sin dibujar un personaje por agente.
 *
 * Vista: cenital para el suelo y las salas, con personajes y muebles en vista frontal
 * (convencion clasica de los simuladores 2D). Es la unica vista del proyecto.
 */
